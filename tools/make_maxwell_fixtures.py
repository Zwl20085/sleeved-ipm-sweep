"""Generate the Maxwell reference fixtures in ``tests/fixtures/maxwell_ref``.

Usage (needs the author's original Maxwell projects and ``shapely``; no Ansys licence)::

    python tools/make_maxwell_fixtures.py --icem PATH/TO/ICEM_project.aedt [--out tests/fixtures/maxwell_ref]

For each sleeved rotor (bridged, bridgeless) the saved state and the variable sets in
:data:`VARIANTS` are replayed with :mod:`maxwell_ref` and written as one JSON file per state:
exact outlines of the lamination faces (outer loop + holes), the four magnets and the sleeve
in the pole frame (d-axis on +x), the derived magnet lengths ``RD_Lpm_lay1/2``, and the
package parameters that reproduce the state.

The stator fixture ``stator_saved.json`` is not regenerated by this script: the stator of the
sleeved designs is a history-free body that the replay cannot rebuild (see the fixtures'
README).

Segments: ``["L", x0, y0, x1, y1]``, ``["A", x0, y0, x1, y1, cx, cy, r, sweep_deg]`` and,
for equation-based curves, ``["C", x0, y0, x1, y1, [[x, y] * 9]]`` (9 points at uniform
curve parameter from start to end). Coordinates in mm, rounded to 1e-10 mm.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from maxwell_ref import geom2d as g  # noqa: E402
from maxwell_ref.model import build, load_design, mm, nominal_naming  # noqa: E402

ROT = g.Affine.rotation(math.radians(-22.5))   # model frame (d-axis at 22.5 deg) -> pole frame
DIGITS = 10

# Maxwell variable -> package parameter (value in mm unless noted)
PARAM_OF = {"Wcf": "sleeve_thickness", "RD_WO_lay1": "pm1_bridge_thickness", "RD_WO_lay2": "pm2_bridge_thickness",
            "RD_FB_lay1": "pm1_rib_half_width", "RD_FB_lay2": "pm2_web_width", "w_tip": "lip_depth"}

ROTORS = {
    "sleeved_bridged": ("01_ICEM_01_simplerotor", "Polyline4", "CF"),
    "sleeved_bridgeless": ("02_ICEM_01_teslamotor1", "Polyline4", "CF"),
}
MAGNETS = ("PMoutline", "PMoutline_2", "PMoutline_1", "PMoutline_1_1")

# Variable sets (Maxwell expressions) spanning the original sweep ranges:
# Wcf 0.5-2, RD_WO_lay* 0.5-1.5, RD_FB_lay* 0.5-1.5, w_tip 0.5-2 mm.
VARIANTS: dict[str, list[dict[str, str]]] = {
    "sleeved_bridged": [
        {"Wcf": "0.5mm"},
        {"Wcf": "1mm", "RD_WO_lay1": "0.5mm", "RD_WO_lay2": "0.5mm"},
        {"Wcf": "1.5mm", "RD_WO_lay1": "1.5mm", "RD_WO_lay2": "1.5mm"},
        {"RD_FB_lay1": "0.5mm", "RD_FB_lay2": "0.5mm"},
        {"Wcf": "1mm", "RD_FB_lay1": "1.5mm", "RD_FB_lay2": "1.5mm"},
        {"Wcf": "0.5mm", "RD_WO_lay1": "1.5mm", "RD_WO_lay2": "0.5mm", "RD_FB_lay1": "0.5mm", "RD_FB_lay2": "1.5mm"},
        {"Wcf": "2mm", "RD_WO_lay1": "0.5mm", "RD_WO_lay2": "1.5mm", "RD_FB_lay1": "1.5mm", "RD_FB_lay2": "0.5mm"},
    ],
    "sleeved_bridgeless": [
        {"Wcf": "2mm"},
        {"w_tip": "0.5mm"},
        {"Wcf": "1mm", "w_tip": "2mm"},
        {"Wcf": "1.5mm", "RD_WO_lay1": "1mm", "RD_WO_lay2": "1mm"},
        {"Wcf": "1mm", "w_tip": "1.5mm", "RD_WO_lay1": "0.5mm", "RD_WO_lay2": "1.5mm"},
        {"Wcf": "2mm", "w_tip": "0.5mm", "RD_WO_lay1": "1.5mm", "RD_WO_lay2": "0.5mm"},
    ],
}


def _r(v: float) -> float:
    return round(float(v), DIGITS)


def seg_json(s) -> list:
    d = s.describe()
    p0, p1 = d["p0"], d["p1"]
    head = [_r(p0[0]), _r(p0[1]), _r(p1[0]), _r(p1[1])]
    if d["type"] == "line":
        return ["L", *head]
    if d["type"] == "arc":
        return ["A", *head, _r(d["center"][0]), _r(d["center"][1]), _r(d["radius"]), _r(d["sweep_deg"])]
    return ["C", *head, [[_r(q[0]), _r(q[1])] for q in (s.at(k / 8) for k in range(9))]]


def body_json(body) -> list:
    faces = []
    for f in body.faces:
        faces.append({"area": _r(g.face_area(f)), "outer": [seg_json(s) for s in f.outer],
                      "holes": [[seg_json(s) for s in h] for h in f.holes]})
    return faces


def params_of(overrides: dict[str, str], saved: dict[str, float]) -> dict[str, float]:
    out = dict(saved)
    for k, v in overrides.items():
        out[PARAM_OF[k]] = float(v.replace("mm", ""))
    return out


def saved_params(ev, topology: str) -> dict[str, float]:
    """Package parameters of the saved state that the topology defaults do not already hold."""
    out = {"sleeve_thickness": _r(mm(ev, "Wcf"))}
    if topology == "sleeved_bridgeless":
        out["lip_depth"] = _r(mm(ev, "w_tip"))
    return out


def state_json(gm, ctx, topology: str, rotor: str, sleeve: str, overrides: dict, saved) -> dict:
    ev = gm.ev
    regions = {"lamination": body_json(gm.final_body(gm.part_by_name(rotor).pid).transform(ROT)),
               "magnets": [body_json(gm.final_body(gm.part_by_name(n).pid).transform(ROT))[0] for n in MAGNETS],
               "sleeve": body_json(gm.final_body(gm.part_by_name(sleeve).pid).transform(ROT))[0]}
    return {"topology": topology, "design": ctx.design, "maxwell_overrides": overrides,
           "params": params_of(overrides, saved),
           "derived": {"RD_Lpm_lay1": _r(mm(ev, "RD_Lpm_lay1")), "RD_Lpm_lay2": _r(mm(ev, "RD_Lpm_lay2"))},
           "regions": regions}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--icem", required=True, help="the ICEM project .aedt (designs 01_/02_ICEM_01_*)")
    ap.add_argument("--out", default=str(HERE.parent / "tests" / "fixtures" / "maxwell_ref"))
    ap.add_argument("--only", nargs="*", default=list(ROTORS), help="topologies to generate")
    a = ap.parse_args(argv)
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    index = []
    for topology in a.only:
        design, rotor, sleeve = ROTORS[topology]
        ctx = load_design(a.icem, design)
        gm0, naming = nominal_naming(ctx, [rotor, *MAGNETS, sleeve])  # clone numbering for the variable sets
        saved = saved_params(gm0.ev, topology)
        for i, ov in enumerate([{}] + VARIANTS[topology]):
            tag = "saved" if not ov else f"v{i}"
            name = f"{topology}_{tag}.json"
            print(f"{name}: replaying {ov or 'saved state'}", flush=True)
            try:
                gm = gm0 if not ov else build(ctx, ov, naming)
                doc = state_json(gm, ctx, topology, rotor, sleeve, ov, saved)
            except Exception as e:  # noqa: BLE001 - report and continue with the other states
                print(f"{name}: replay failed: {type(e).__name__}: {e}")
                index.append({"file": name, "maxwell_overrides": ov, "status": f"replay failed: {e}"})
                continue
            (out / name).write_text(json.dumps(doc, separators=(",", ":")) + "\n", encoding="utf-8")
            index.append({"file": name, "maxwell_overrides": ov, "status": "ok", "derived": doc["derived"]})
            print(f"{name}: Lpm = {doc['derived']}")
    stator = out / "stator_saved.json"
    if stator.exists():  # kept from an earlier generation; listed so that the index stays complete
        index.insert(0, {"file": stator.name, "maxwell_overrides": {}, "status": "ok"})
    (out / "index.json").write_text(json.dumps(index, indent=1) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
