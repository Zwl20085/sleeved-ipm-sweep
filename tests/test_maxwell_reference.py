"""The package geometry reproduces the author's Maxwell models (fixtures in
tests/fixtures/maxwell_ref, generated by tools/make_maxwell_fixtures.py).

Tolerances: every vertex, arc centre and radius, and every curve sample within 1e-6 mm; every
region area within 1e-6 relative; derived magnet lengths equal RD_Lpm_lay1/2 within 1e-6 mm.

Two deliberate deviations, both in the bridgeless rotor only (docs/methods.md, 1.3 and 1.4):

1. Rib cut. The model cuts the 0.1 mm centre ribs with two hand-placed prisms whose q-side
   end is a V notch with a hard-coded apex (one of them 0.007 mm off the d-axis). The package
   derives the cut instead (convex hull of the slot's inner-end corners, the slot corner P5
   and the magnet's inner corners that lie before the slot end, mirrored). The two notches
   are therefore flat in the package.
2. Layer-1 OD openings. The model places them from ``angle_temp_lay1`` minus 1.5 deg, and its
   expression for ``angle_temp_lay1`` uses the layer-2 d-axis crossing in the x term (a typo).
   The package uses the true angle where the layer-1 magnet centre line meets the OD and no
   shift, as for layer 2. The layer-1 openings therefore sit at different angles.

The test checks that the notch segments and the layer-1 opening segments are the ONLY
unmatched segments; that each notch apex lies on the q-body side of the package's flat edge;
that the model's layer-1 opening edges lie exactly where the model's expression puts them and
the package's exactly at the true angle, and that every unmatched opening segment matches a
package segment once its opening-edge end points are moved from the model's to the package's
edge angles; and that the lamination areas differ by exactly the notch polygons and the moved
lip sectors.
"""

import math

import pytest
from maxwell_compare import STATOR_FIXTURE, _pkg_seg, _seg_dev, compare_fixture, compare_stator, fixture_names, load

from sipm.geometry import build_rotor
from sipm.geometry.primitives import chain_area, polygon_chain
from sipm.geometry.rotor import opening_angles
from sipm.params import default_params

TOL = 1e-6
NAMES = fixture_names()
BRIDGELESS = [n for n in NAMES if n.startswith("sleeved_bridgeless")]
MODEL_PM1_SHIFT = 1.5  # deg, "1.5deg" in the model's Angle_rib3


def test_fixture_set_complete():
    by = {t: [n for n in NAMES if n.startswith(t + "_")] for t in ("sleeved_bridged", "sleeved_bridgeless")}
    assert sorted(sum(by.values(), [])) == NAMES
    assert len([n for n in by["sleeved_bridged"] if "_v" in n]) >= 6
    assert len([n for n in by["sleeved_bridgeless"] if "_v" in n]) >= 6


@pytest.mark.parametrize("name", NAMES)
def test_derived_magnet_lengths_equal_maxwell(name):
    doc = load(name)
    _, rp = compare_fixture(doc)
    assert rp.layers[0].length == pytest.approx(doc["derived"]["RD_Lpm_lay1"], abs=1e-6)
    assert rp.layers[1].length == pytest.approx(doc["derived"]["RD_Lpm_lay2"], abs=1e-6)


@pytest.mark.parametrize("name", [n for n in NAMES if not n.startswith("sleeved_bridgeless")])
def test_outlines_reproduce_maxwell(name):
    rep, _ = compare_fixture(load(name), TOL)
    assert not rep.problems, rep.problems
    assert not rep.unmatched, rep.unmatched[:5]
    assert rep.max_dev < TOL
    assert rep.max_area_rel < 1e-6


def test_stator_reproduces_maxwell():
    rep = compare_stator(load(STATOR_FIXTURE), TOL)
    assert not rep.problems and not rep.unmatched
    assert rep.max_area_rel < 1e-6


def _notches(segs):
    """Group fixture lines into V notches: apex -> [the two other end points]."""
    assert all(s[0] == "L" for s in segs), segs
    count: dict = {}
    for s in segs:
        for q in (tuple(s[1:3]), tuple(s[3:5])):
            count[q] = count.get(q, 0) + 1
    out = {}
    for apex in (q for q, n in count.items() if n == 2):
        legs = [s for s in segs if apex in (tuple(s[1:3]), tuple(s[3:5]))]
        out[apex] = [tuple(s[3:5]) if tuple(s[1:3]) == apex else tuple(s[1:3]) for s in legs]
    return out


def _model_pm1_opening(p) -> tuple[float, float]:
    """Layer-1 opening (lo, hi) in rad as the model places it: angle_temp_lay1 as written in
    the model (x term with RD_xpm_lay2) minus 1.5 deg, the opening width towards the d-axis."""
    th = math.radians(p.pm1_angle) / 2
    s, c = math.sin(th), math.cos(th)
    x1, x2 = p.pm1_d_crossing, p.pm2_d_crossing
    root = math.sqrt(p.r_lam ** 2 - (x1 * s) ** 2)
    hi = math.atan2(-x1 * s * c + s * root, x2 * s * s + c * root) - math.radians(MODEL_PM1_SHIFT)
    return hi - math.radians(p.pm1_opening_angle), hi


def _on_edge(q, ang: float, radii) -> bool:
    """q lies at polar angle +-ang on one of the radii (within TOL mm)."""
    r = math.hypot(*q)
    return any(abs(r - R) < TOL for R in radii) and abs(abs(math.atan2(q[1], q[0])) - ang) * r < TOL


def _moved(seg: list, edges: dict, radii) -> list:
    """Fixture segment with every end point on a model opening edge moved to the package edge."""
    out = list(seg)
    for i in (1, 3):
        q = seg[i:i + 2]
        for a_model, a_pkg in edges.items():
            if _on_edge(q, a_model, radii):
                r, sign = math.hypot(*q), math.copysign(1.0, q[1])
                out[i:i + 2] = [r * math.cos(a_pkg), sign * r * math.sin(a_pkg)]
    return out


def test_true_opening_reference_is_on_the_magnet_centre_line_and_the_od():
    rp = build_rotor(default_params("sleeved_bridgeless"))
    for L in rp.layers:
        a = L.scalars["opening_reference"]
        q = (rp.r_lam * math.cos(a), rp.r_lam * math.sin(a))
        u = L.u
        assert abs((q[0] - L.inp.xpm) * u[1] - q[1] * u[0]) < 1e-9          # on the centre line
        assert (q[0] - L.inp.xpm) * u[0] + q[1] * u[1] > 0                   # beyond the d-axis crossing
        assert opening_angles(rp.p, L)[1] == pytest.approx(a, abs=1e-15)    # shift 0: q-side edge at it
    # saved state: true 12.394 deg; the model's expression gives 13.616 deg
    assert math.degrees(rp.layers[0].scalars["opening_reference"]) == pytest.approx(12.394, abs=1e-3)
    assert math.degrees(_model_pm1_opening(rp.p)[1]) + MODEL_PM1_SHIFT == pytest.approx(13.616, abs=1e-3)


@pytest.mark.parametrize("name", BRIDGELESS)
def test_bridgeless_reproduces_maxwell_except_rib_cut_and_layer1_openings(name):
    doc = load(name)
    rep, rp = compare_fixture(doc, TOL)
    p = rp.p
    assert rep.max_dev < TOL
    r_in = rp.r_lam - p.lip_depth
    radii = (rp.r_lam, r_in)
    lo_m, hi_m = _model_pm1_opening(p)
    lo_t, hi_t = opening_angles(p, rp.layers[0])
    assert p.pm1_opening_shift == 0.0 and hi_t == rp.layers[0].scalars["opening_reference"]
    edges = {lo_m: lo_t, hi_m: hi_t}
    # ---- deviation 2: layer-1 openings ---------------------------------------------------
    opening = [s for _, s in rep.unmatched
               if any(_on_edge(s[i:i + 2], a, radii) for i in (1, 3) for a in edges)]
    others = [s for _, s in rep.unmatched if s not in opening]
    # per side: middle-piece OD arc, edge line, lip arc; pole-cap lip arc, edge line; one cap OD arc
    assert len(opening) == 11, opening
    for a in edges:  # each model edge is a radial line r_in .. r_lam at +-a
        lines = [s for s in opening if s[0] == "L" and _on_edge(s[1:3], a, radii) and _on_edge(s[3:5], a, radii)]
        assert len(lines) == 2, (math.degrees(a), lines)
    pkg = [_pkg_seg(s) for f in rp.lamination for ch in (f.outer, *f.holes) for s in ch]
    for s in opening:
        assert min(_seg_dev(_moved(s, edges, radii), m) for m in pkg) < TOL, s
    # ---- deviation 1: rib-cut notches ------------------------------------------------------
    notches = {a: b for a, b in _notches(others).items() if abs(a[1]) < 0.01}
    assert len(notches) == 2 and len(others) == 6, others  # as before the opening change
    # ---- areas -----------------------------------------------------------------------------
    fx = sorted(doc["regions"]["lamination"], key=lambda f: -f["area"])
    pk = sorted(rp.lamination, key=lambda f: -f.area())
    assert len(fx) == len(pk) == 3

    def has_edge_line(face, a):
        return any(s.kind == "line" and _on_edge(s.start(), a, radii) and _on_edge(s.end(), a, radii)
                   for s in face.outer)

    cap = [i for i, f in enumerate(pk) if has_edge_line(f, lo_t)]
    middle = [i for i, f in enumerate(pk) if has_edge_line(f, hi_t)]
    assert len(cap) == len(middle) == 1 and cap != middle
    body = ({0, 1, 2} - set(cap) - set(middle)).pop()
    # lip sector moved per side: the cap gains [lo_m, lo_t], the middle piece loses [hi_m, hi_t]
    assert lo_t - lo_m == pytest.approx(hi_t - hi_m, abs=1e-15)
    sector = 0.5 * (rp.r_lam ** 2 - r_in ** 2) * (hi_t - hi_m)
    expected = {cap[0]: 2 * sector, middle[0]: -2 * sector, body: 0.0}
    for L, piece in ((rp.layers[0], middle[0]), (rp.layers[1], body)):
        k = L.inp.k
        apex = min(notches, key=lambda a: abs(a[0] - L.p("P5")[0]))
        a_up, a_lo = sorted(notches[apex], key=lambda q: -q[1])
        # package side of the cut between the same two corners: hull vertices left of the corners
        hull = [s.start() for s in _rib_cut(rp, k)]
        inner = [q for q in hull if q[0] < a_up[0] - 1e-9]
        assert all(apex[0] < q[0] for q in inner + [a_up]), "the model's notch lies on the q-body side"
        poly = [a_up, apex, a_lo] + sorted(inner, key=lambda q: q[1])
        expected[piece] += abs(chain_area(polygon_chain(poly)))
    for i, (f_pk, f_fx) in enumerate(zip(pk, fx)):
        assert f_pk.area() - f_fx["area"] == pytest.approx(expected[i], rel=1e-6, abs=1e-6), i


def _rib_cut(rp, k):
    from sipm.geometry.rotor import _rib_cut as cut

    return cut(rp.p, rp.layers[k - 1])
